(function ($) {
  "use strict";

  var scheduleVersionCreateDraft = null;

  var SCHEDULE_MATCHING_PLANS_URL = "/schedule/matching-plans";

  function getDefaultTeamgroupID() {
    var sel = document.getElementById("scheduleWindowTeamgroup");
    if (!sel || !sel.options.length) {
      return "";
    }
    return String(sel.options[0].value);
  }

  function getProductNameById(productId) {
    var grid = document.getElementById("scheduleWindowSystemsGrid");
    if (!grid) {
      return "系统";
    }
    var label = grid.querySelector('label[data-product-id="' + productId + '"]');
    return label ? label.getAttribute("data-product-name") || "系统" : "系统";
  }

  function buildDefaultScheduleWindowNameFromOnline(online) {
    var d = String(online || "").slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) {
      return "新版本窗口";
    }
    return d.slice(2, 4) + "-" + d.slice(5, 7) + d.slice(8, 10) + "窗口";
  }

  function createScheduleVersionCreateDraft() {
    return {
      name: "",
      start: "",
      end: "",
      teamgroupId: getDefaultTeamgroupID(),
      windowType: "regular",
      planTestDone: "",
      testDone: "",
      acceptDone: "",
      online: "",
      productIds: [],
      systemPlanDraft: {},
      systemPlanMatch: {},
      _nameAutoGenerated: true,
    };
  }

  function hasValidScheduleOnlineDate(draft) {
    return /^\d{4}-\d{2}-\d{2}$/.test(String((draft || {}).online || "").slice(0, 10));
  }

  function formatScheduleDate(value) {
    var text = String(value == null ? "" : value).slice(0, 10);
    return /^\d{4}-\d{2}-\d{2}$/.test(text) ? text : "-";
  }

  function getScheduleVersionCreateDraft() {
    if (!scheduleVersionCreateDraft) {
      scheduleVersionCreateDraft = createScheduleVersionCreateDraft();
    }
    return scheduleVersionCreateDraft;
  }

  function getScheduleVersionModalDraft(isActive) {
    return isActive ? getScheduleVersionCreateDraft() : null;
  }

  function getScheduleVersionModalWindowMeta() {
    var d = getScheduleVersionCreateDraft();
    return {
      online: d.online || "",
      windowName: d.name || buildDefaultScheduleWindowNameFromOnline(d.online),
      planTestDone: d.planTestDone || "",
      testDone: d.testDone || "",
      acceptDone: d.acceptDone || "",
    };
  }

  function syncScheduleDraftPlanNamesFromWindow(d) {
    var windowName = d.name || buildDefaultScheduleWindowNameFromOnline(d.online);
    Object.keys(d.systemPlanDraft || {}).forEach(function (key) {
      var row = d.systemPlanDraft[key];
      if (row && !row._customName) {
        row.planName = windowName;
      }
    });
  }

  function applyScheduleOnlineDerivedFields(d, online) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(online)) {
      return false;
    }
    d.name = buildDefaultScheduleWindowNameFromOnline(online);
    d._nameAutoGenerated = true;
    d.end = online;
    syncScheduleDraftPlanNamesFromWindow(d);
    return true;
  }

  function clearScheduleOnlineDerivedFields(d) {
    if (d._nameAutoGenerated) {
      d.name = "";
    }
    d.end = "";
    Object.keys(d.systemPlanMatch || {}).forEach(function (key) {
      delete d.systemPlanMatch[key];
    });
  }

  function ensureScheduleModalSystemPlanDraft(productId, productName) {
    var d = getScheduleVersionCreateDraft();
    var meta = getScheduleVersionModalWindowMeta();
    var key = String(productId);
    if (!d.systemPlanDraft) {
      d.systemPlanDraft = {};
    }
    if (!d.systemPlanDraft[key]) {
      d.systemPlanDraft[key] = {
        syncCreate: true,
        planName: meta.windowName || buildDefaultScheduleWindowNameFromOnline(meta.online),
        planBegin: d.start || "",
        productName: productName || getProductNameById(productId),
      };
    }
    return d.systemPlanDraft[key];
  }

  function cloneScheduleTemplate(id) {
    var tpl = document.getElementById(id);
    if (!tpl || !tpl.content || !tpl.content.firstElementChild) {
      return null;
    }
    return document.importNode(tpl.content.firstElementChild, true);
  }

  function setFieldText(root, selector, value) {
    var el = root.querySelector(selector);
    if (el) {
      el.textContent = value == null ? "" : String(value);
    }
  }

  function renderSchedulePlanGrid(isActive) {
    var d = getScheduleVersionModalDraft(isActive);
    var grid = document.getElementById("scheduleWindowPlanGrid");
    var emptyEl = document.getElementById("scheduleWindowPlanEmpty");
    if (!grid || !d) {
      return;
    }
    Array.from(grid.querySelectorAll("[data-field='planCard'], .schedule-create-plan-card")).forEach(function (node) {
      node.remove();
    });
    var productIds = d.productIds || [];
    if (!productIds.length) {
      if (emptyEl) {
        emptyEl.style.display = "";
      }
      return;
    }
    if (emptyEl) {
      emptyEl.style.display = "none";
    }
    var meta = getScheduleVersionModalWindowMeta();
    productIds.forEach(function (productId) {
      var key = String(productId);
      var match = (d.systemPlanMatch || {})[key] || {};
      var productName = match.productName || getProductNameById(productId);
      var card = null;

      if (match.loading) {
        card = cloneScheduleTemplate("schedulePlanCardLoading");
      } else if (!hasValidScheduleOnlineDate(d) && !match.error) {
        card = cloneScheduleTemplate("schedulePlanCardPending");
      } else if (match.hasMatch && match.plans && match.plans.length) {
        match.plans.forEach(function (plan) {
          var existing = cloneScheduleTemplate("schedulePlanCardExisting");
          if (!existing) {
            return;
          }
          setFieldText(existing, '[data-field="productName"]', productName);
          setFieldText(existing, '[data-field="planTitle"]', plan.title || "");
          setFieldText(existing, '[data-field="planOnline"]', formatScheduleDate(plan.end || meta.online));
          grid.appendChild(existing);
        });
        return;
      } else {
        var row = ensureScheduleModalSystemPlanDraft(productId, productName);
        card = cloneScheduleTemplate("schedulePlanCardDraft");
        if (!card) {
          return;
        }
        card.setAttribute("data-product-id", String(productId));
        var syncInput = card.querySelector('[data-field="syncCreate"]');
        var planNameInput = card.querySelector('[data-field="planName"]');
        var planNameGroup = card.querySelector('[data-field="planNameGroup"]');
        if (syncInput) {
          syncInput.checked = !!row.syncCreate;
        }
        if (planNameInput) {
          planNameInput.value = row.planName || "";
          planNameInput.disabled = !row.syncCreate;
        }
        if (planNameGroup) {
          planNameGroup.style.opacity = row.syncCreate ? "" : "0.5";
        }
        setFieldText(
          card,
          '[data-field="planMeta"]',
          "里程碑：开始 " +
            formatScheduleDate(row.planBegin || d.start) +
            " / 提测 " +
            formatScheduleDate(meta.planTestDone) +
            " / 测试 " +
            formatScheduleDate(meta.testDone) +
            " / 验收 " +
            formatScheduleDate(meta.acceptDone) +
            " / 上线 " +
            formatScheduleDate(meta.online)
        );
      }

      if (!card) {
        return;
      }
      setFieldText(card, '[data-field="productName"]', productName);
      grid.appendChild(card);
    });
  }

  function syncScheduleDateInputFilledState(root) {
    var scope = root || document.getElementById("scheduleVersionWindowForm") || document;
    scope.querySelectorAll('input[type="date"].form-input').forEach(function (input) {
      if (String(input.value || "").trim()) {
        input.classList.add("has-value");
      } else {
        input.classList.remove("has-value");
      }
    });
  }

  function fillScheduleVersionWindowForm(isActive) {
    var d = getScheduleVersionCreateDraft();
    $("#scheduleWindowOnline").val(d.online || "");
    $("#scheduleWindowName").val(d.name || "");
    $("#scheduleWindowStart").val(d.start || "");
    $("#scheduleWindowEnd").val(d.end || "");
    $("#scheduleWindowTeamgroup").val(d.teamgroupId || getDefaultTeamgroupID());
    $("#scheduleWindowType").val(d.windowType || "regular");
    $("#scheduleWindowPlanTestDone").val(d.planTestDone || "");
    $("#scheduleWindowTestDone").val(d.testDone || "");
    $("#scheduleWindowAcceptDone").val(d.acceptDone || "");

    var selected = new Set((d.productIds || []).map(Number));
    $("#scheduleWindowSystemsGrid input[name='productIds']").each(function () {
      this.checked = selected.has(Number(this.value));
    });

    renderSchedulePlanGrid(isActive);
    syncScheduleDateInputFilledState();
  }

  var scheduleWindowForm = document.getElementById("scheduleVersionWindowForm");
  if (scheduleWindowForm) {
    scheduleWindowForm.addEventListener("change", function (e) {
      var target = e.target;
      if (target && target.type === "date") {
        syncScheduleDateInputFilledState(scheduleWindowForm);
      }
    });
    scheduleWindowForm.addEventListener("input", function (e) {
      var target = e.target;
      if (target && target.type === "date") {
        syncScheduleDateInputFilledState(scheduleWindowForm);
      }
    });
  }

  function fetchMatchingPlansForProduct(productId, productName, isActive) {
    var d = getScheduleVersionCreateDraft();
    var endDate = String(d.online || "").slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(endDate)) {
      return;
    }
    var key = String(productId);
    if (!d.systemPlanMatch) {
      d.systemPlanMatch = {};
    }
    d.systemPlanMatch[key] = { loading: true, productName: productName || getProductNameById(productId) };
    renderSchedulePlanGrid(isActive);

    var query = new URLSearchParams({
      product_id: String(productId),
      end_date: endDate,
    });
    var fetchFn = window.scheduleFetch || window.appFetch || fetch;
    fetchFn(SCHEDULE_MATCHING_PLANS_URL + "?" + query.toString(), {
      method: "GET",
      headers: {
        Accept: "application/json",
        "X-Requested-With": "XMLHttpRequest",
      },
    })
      .then(function (resp) {
        return resp.json().catch(function () {
          return {};
        });
      })
      .then(function (resp) {
        var draft = getScheduleVersionCreateDraft();
        var plans = (resp && resp.plans) || [];
        draft.systemPlanMatch[key] = {
          loading: false,
          productName: productName || getProductNameById(productId),
          hasMatch: !!(resp && resp.has_match),
          plans: plans,
          selectedPlanIds: plans
            .map(function (plan) {
              return Number(plan.id);
            })
            .filter(function (id) {
              return id > 0;
            }),
        };
        if (!resp || !resp.has_match) {
          var pendingDraft = ensureScheduleModalSystemPlanDraft(productId, productName);
          pendingDraft.planName = draft.name || buildDefaultScheduleWindowNameFromOnline(draft.online);
          pendingDraft.planBegin = draft.start || "";
          pendingDraft._customName = false;
          pendingDraft._customBegin = false;
        }
        renderSchedulePlanGrid(isActive);
      })
      .catch(function (err) {
        if (err && err.message === "session expired") {
          return;
        }
        var draft = getScheduleVersionCreateDraft();
        draft.systemPlanMatch[key] = {
          loading: false,
          productName: productName || getProductNameById(productId),
          hasMatch: false,
          plans: [],
          error: true,
        };
        var pendingDraft = ensureScheduleModalSystemPlanDraft(productId, productName);
        pendingDraft.planName = draft.name || buildDefaultScheduleWindowNameFromOnline(draft.online);
        pendingDraft.planBegin = draft.start || "";
        pendingDraft._customName = false;
        pendingDraft._customBegin = false;
        renderSchedulePlanGrid(isActive);
      });
  }

  function refreshMatchingPlansForSelectedProducts(isActive) {
    var d = getScheduleVersionCreateDraft();
    (d.productIds || []).forEach(function (productId) {
      var key = String(productId);
      var name =
        ((d.systemPlanMatch || {})[key] && d.systemPlanMatch[key].productName) ||
        getProductNameById(productId);
      fetchMatchingPlansForProduct(productId, name, isActive);
    });
  }

  window.ScheduleWindowDraft = {
    createDraft: createScheduleVersionCreateDraft,
    getDraft: getScheduleVersionCreateDraft,
    setDraft: function (draft) {
      scheduleVersionCreateDraft = draft;
    },
    resetDraft: function () {
      scheduleVersionCreateDraft = null;
    },
    fillForm: fillScheduleVersionWindowForm,
    applyOnlineDerivedFields: applyScheduleOnlineDerivedFields,
    clearOnlineDerivedFields: clearScheduleOnlineDerivedFields,
    syncPlanNamesFromWindow: syncScheduleDraftPlanNamesFromWindow,
    ensureSystemPlanDraft: ensureScheduleModalSystemPlanDraft,
    fetchMatchingPlans: fetchMatchingPlansForProduct,
    refreshMatchingPlans: refreshMatchingPlansForSelectedProducts,
    renderPlanGrid: renderSchedulePlanGrid,
    getModalDraft: getScheduleVersionModalDraft,
    hasValidOnlineDate: hasValidScheduleOnlineDate,
    getProductName: getProductNameById,
    getDefaultTeamgroupID: getDefaultTeamgroupID,
  };
})(jQuery);
