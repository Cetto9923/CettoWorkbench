(function ($) {
  "use strict";

  var scheduleVersionWindowModalMode = "idle";
  var scheduleEditingWindowId = null;
  var draftApi = window.ScheduleWindowDraft;

  var SCHEDULE_CREATE_WINDOW_URL = "/schedule/windows";
  var VERSION_WINDOW_MODAL_IDS = ["scheduleVersionWindowModal", "scheduleVersionWindowModalOverlay"];

  if (!draftApi) {
    return;
  }

  function isModalActive() {
    return scheduleVersionWindowModalMode === "create" || scheduleVersionWindowModalMode === "edit";
  }

  function scheduleWindowURL(windowId) {
    var id = Number(windowId);
    return id ? SCHEDULE_CREATE_WINDOW_URL + "/" + id : SCHEDULE_CREATE_WINDOW_URL;
  }

  function openScheduleCreateVersionWindowModal() {
    scheduleVersionWindowModalMode = "create";
    scheduleEditingWindowId = null;
    draftApi.setDraft(draftApi.createDraft());
    $("#scheduleVersionWindowModalTitle").text("新建版本窗口");
    $("#scheduleVersionWindowModalSaveBtn").text("保存");
    draftApi.fillForm(true);
    window.openShowModals(VERSION_WINDOW_MODAL_IDS);
  }

  function isSessionExpiredError(err) {
    return !!(err && err.message === "session expired");
  }

  function scheduleRequestFetch(url, options) {
    var fetchFn = window.scheduleFetch || window.appFetch || fetch;
    return fetchFn(url, options);
  }

  function openScheduleEditVersionWindowModal(windowId) {
    var id = Number(windowId);
    if (!id) {
      return;
    }
    if (typeof window.closeAllScheduleWindowCardMenus === "function") {
      window.closeAllScheduleWindowCardMenus();
    }
    var headers = { Accept: "application/json" };

    scheduleRequestFetch(scheduleWindowURL(id), { method: "GET", headers: headers })
      .then(function (resp) {
        return resp
          .json()
          .catch(function () {
            return {};
          })
          .then(function (data) {
            return { ok: resp.ok, data: data || {} };
          });
      })
      .then(function (result) {
        if (!result.data || !result.data.success) {
          if (typeof window.showToast === "function") {
            window.showToast((result.data && result.data.error) || "加载窗口详情失败", "error");
          }
          return;
        }
        scheduleVersionWindowModalMode = "edit";
        scheduleEditingWindowId = id;
        draftApi.setDraft(populateDraftFromWindowDetail(result.data));
        $("#scheduleVersionWindowModalTitle").text("编辑版本窗口");
        $("#scheduleVersionWindowModalSaveBtn").text("保存");
        draftApi.fillForm(true);
        window.openShowModals(VERSION_WINDOW_MODAL_IDS);
      })
      .catch(function (err) {
        if (isSessionExpiredError(err)) {
          return;
        }
        if (typeof window.showToast === "function") {
          window.showToast("加载窗口详情失败，请稍后重试", "error");
        }
      });
  }

  function closeScheduleVersionWindowModal() {
    window.closeShowModals(VERSION_WINDOW_MODAL_IDS);
    scheduleVersionWindowModalMode = "idle";
    scheduleEditingWindowId = null;
    draftApi.resetDraft();
    $("#scheduleVersionWindowModalSaveBtn").text("保存");
  }

  function populateDraftFromWindowDetail(detail) {
    var d = draftApi.createDraft();
    d.online = detail.releaseDate || "";
    d.name = detail.name || "";
    d.start = detail.startDate || "";
    d.end = detail.releaseDate || "";
    d.teamgroupId = detail.teamgroupId ? String(detail.teamgroupId) : draftApi.getDefaultTeamgroupID();
    d._nameAutoGenerated = false;
    d.productIds = (detail.products || [])
      .map(function (item) {
        return Number(item.productId);
      })
      .filter(function (id) {
        return id > 0;
      });

    (detail.products || []).forEach(function (item) {
      var key = String(item.productId);
      var productName = item.productName || draftApi.getProductName(item.productId);
      if (item.hasMatch && item.plans && item.plans.length) {
        d.systemPlanMatch[key] = {
          loading: false,
          productName: productName,
          hasMatch: true,
          plans: item.plans,
          selectedPlanIds: item.plans
            .map(function (plan) {
              return Number(plan.id);
            })
            .filter(function (id) {
              return id > 0;
            }),
        };
        return;
      }
      d.systemPlanMatch[key] = { loading: false, productName: productName, hasMatch: false, plans: [] };
      d.systemPlanDraft[key] = {
        syncCreate: !!item.syncPlan,
        planName: item.planTitle || detail.name || "",
        planBegin: detail.startDate || "",
        productName: productName,
      };
    });
    return d;
  }

  function collectScheduleCreateSavePayload() {
    var d = draftApi.getDraft();
    return {
      releaseDate: d.online || "",
      name: d.name || "",
      startDate: d.start || "",
      endDate: d.end || "",
      teamgroupId: d.teamgroupId || "",
      windowType: d.windowType || "regular",
      planTestDone: d.planTestDone || "",
      testDone: d.testDone || "",
      acceptDone: d.acceptDone || "",
      products: (d.productIds || []).map(function (productId) {
        var key = String(productId);
        var match = (d.systemPlanMatch || {})[key] || {};
        var row = (d.systemPlanDraft || {})[key] || {};
        return {
          productId: Number(productId),
          selectedPlanIds: (match.selectedPlanIds || []).map(Number),
          syncPlan: !!row.syncCreate,
          planTitle: row.planName || "",
          planBegin: row.planBegin || d.start || "",
        };
      }),
    };
  }

  function bindScheduleVersionWindowForm() {
    var form = document.getElementById("scheduleVersionWindowForm");
    if (!form) {
      return;
    }

    function refreshUI() {
      draftApi.fillForm(isModalActive());
    }

    function updateScheduleCreateDraftField(field, value) {
      var d = draftApi.getDraft();
      d[field] = value;
      if (field === "online") {
        var online = String(value || "").slice(0, 10);
        if (draftApi.applyOnlineDerivedFields(d, online)) {
          if ((d.productIds || []).length) {
            draftApi.refreshMatchingPlans(isModalActive());
          }
        } else {
          draftApi.clearOnlineDerivedFields(d);
        }
        refreshUI();
        return;
      }
      if (field === "name") {
        d._nameAutoGenerated = false;
        draftApi.syncPlanNamesFromWindow(d);
        refreshUI();
        return;
      }
      if (field === "start") {
        draftApi.renderPlanGrid(isModalActive());
      }
    }

    form.addEventListener("change", function (e) {
      var target = e.target;
      if (!target || !target.name) {
        return;
      }
      if (target.name === "productIds" && target.type === "checkbox") {
        var label = target.closest("label[data-product-id]");
        var productId = label ? label.getAttribute("data-product-id") : target.value;
        var productName = label ? label.getAttribute("data-product-name") : draftApi.getProductName(productId);
        var d = draftApi.getModalDraft(isModalActive());
        if (!d) {
          return;
        }
        var id = Number(productId);
        var set = new Set((d.productIds || []).map(Number));
        if (target.checked) {
          set.add(id);
          d.productIds = Array.from(set);
          if (draftApi.hasValidOnlineDate(d)) {
            draftApi.fetchMatchingPlans(id, productName, isModalActive());
          } else {
            draftApi.renderPlanGrid(isModalActive());
          }
        } else {
          set.delete(id);
          d.productIds = Array.from(set);
          delete (d.systemPlanDraft || {})[String(id)];
          delete (d.systemPlanMatch || {})[String(id)];
          draftApi.renderPlanGrid(isModalActive());
          if (!d.productIds.length) {
            var emptyEl = document.getElementById("scheduleWindowPlanEmpty");
            if (emptyEl) {
              emptyEl.style.display = "";
            }
          }
        }
        return;
      }
      updateScheduleCreateDraftField(target.name, target.value);
    });

    form.addEventListener("input", function (e) {
      var target = e.target;
      if (target && target.name === "name") {
        updateScheduleCreateDraftField("name", target.value);
      }
    });

    var planGrid = document.getElementById("scheduleWindowPlanGrid");
    if (planGrid) {
      planGrid.addEventListener("change", function (e) {
        var target = e.target;
        if (!target || target.getAttribute("data-field") !== "syncCreate") {
          return;
        }
        var card = target.closest("[data-product-id]");
        if (!card) {
          return;
        }
        var row = draftApi.ensureSystemPlanDraft(card.getAttribute("data-product-id"), "");
        row.syncCreate = !!target.checked;
        var planNameInput = card.querySelector('[data-field="planName"]');
        var planNameGroup = card.querySelector('[data-field="planNameGroup"]');
        if (planNameInput) {
          planNameInput.disabled = !row.syncCreate;
        }
        if (planNameGroup) {
          planNameGroup.style.opacity = row.syncCreate ? "" : "0.5";
        }
      });

      planGrid.addEventListener("input", function (e) {
        var target = e.target;
        if (!target || target.getAttribute("data-field") !== "planName") {
          return;
        }
        var card = target.closest("[data-product-id]");
        if (!card) {
          return;
        }
        var row = draftApi.ensureSystemPlanDraft(card.getAttribute("data-product-id"), "");
        row.planName = target.value;
        row._customName = true;
      });
    }
  }

  function validateScheduleCreateSavePayload(payload) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(payload.releaseDate || "").slice(0, 10))) {
      return "请填写预计上线日期";
    }
    if (!String(payload.name || "").trim()) {
      return "请填写窗口名称";
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(payload.startDate || "").slice(0, 10))) {
      return "请填写窗口开始日期";
    }
    if (!Number(payload.teamgroupId)) {
      return "请选择敏捷小组";
    }
    return "";
  }

  function submitScheduleWindowRequest(method, url, payload) {
    return scheduleRequestFetch(url, {
      method: method,
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      body: JSON.stringify({
        releaseDate: payload.releaseDate,
        name: payload.name,
        startDate: payload.startDate,
        teamgroupId: Number(payload.teamgroupId),
        products: (payload.products || []).map(function (item) {
          return {
            productId: Number(item.productId),
            syncPlan: !!item.syncPlan,
            planTitle: item.planTitle || "",
          };
        }),
      }),
    }).then(function (resp) {
      return resp
        .json()
        .catch(function () {
          return {};
        })
        .then(function (data) {
          return { ok: resp.ok, data: data || {} };
        });
    });
  }

  function saveScheduleVersionWindowModal() {
    if (!isModalActive()) {
      return null;
    }
    var payload = collectScheduleCreateSavePayload();
    var validationError = validateScheduleCreateSavePayload(payload);
    if (validationError) {
      if (typeof window.showToast === "function") {
        window.showToast(validationError, "error");
      }
      return null;
    }
    var isEdit = scheduleVersionWindowModalMode === "edit" && Number(scheduleEditingWindowId) > 0;
    var method = isEdit ? "PUT" : "POST";
    var url = isEdit ? scheduleWindowURL(scheduleEditingWindowId) : SCHEDULE_CREATE_WINDOW_URL;
    var successMessage = isEdit ? "版本窗口更新成功" : "版本窗口保存成功";

    submitScheduleWindowRequest(method, url, payload)
      .then(function (result) {
        if (result.data && result.data.success) {
          if (typeof window.showToast === "function") {
            window.showToast(result.data.message || successMessage, "success");
          }
          closeScheduleVersionWindowModal();
          if (result.data.redirectUrl) {
            window.location.href = result.data.redirectUrl;
          }
          return;
        }
        if (typeof window.showToast === "function") {
          window.showToast(
            (result.data && result.data.error) || (result.ok ? "保存失败" : "保存失败，请稍后重试"),
            "error"
          );
        }
      })
      .catch(function (err) {
        if (isSessionExpiredError(err)) {
          return;
        }
        if (typeof window.showToast === "function") {
          window.showToast("保存失败，请稍后重试", "error");
        }
      });
    return payload;
  }

  function deleteScheduleVersionWindow(windowId, windowName) {
    var id = Number(windowId);
    if (!id) {
      return;
    }
    if (typeof window.closeAllScheduleWindowCardMenus === "function") {
      window.closeAllScheduleWindowCardMenus();
    }
    var label = String(windowName || "").trim() || "该窗口";
    if (!window.confirm("确定要删除窗口 " + label + " 吗？")) {
      return;
    }
    scheduleRequestFetch(scheduleWindowURL(id), {
      method: "DELETE",
      headers: { Accept: "application/json" },
    })
      .then(function (resp) {
        return resp
          .json()
          .catch(function () {
            return {};
          })
          .then(function (data) {
            return { ok: resp.ok, data: data || {} };
          });
      })
      .then(function (result) {
        if (result.data && result.data.success) {
          if (typeof window.showToast === "function") {
            window.showToast(result.data.message || "版本窗口已删除", "success");
          }
          if (result.data.redirectUrl) {
            window.location.href = result.data.redirectUrl;
          }
          return;
        }
        if (typeof window.showToast === "function") {
          window.showToast(
            (result.data && result.data.error) || (result.ok ? "删除失败" : "删除失败，请稍后重试"),
            "error"
          );
        }
      })
      .catch(function (err) {
        if (isSessionExpiredError(err)) {
          return;
        }
        if (typeof window.showToast === "function") {
          window.showToast("删除失败，请稍后重试", "error");
        }
      });
  }

  window.openScheduleCreateVersionWindowModal = openScheduleCreateVersionWindowModal;
  window.openScheduleEditVersionWindowModal = openScheduleEditVersionWindowModal;
  window.closeScheduleVersionWindowModal = closeScheduleVersionWindowModal;
  window.saveScheduleVersionWindowModal = saveScheduleVersionWindowModal;
  window.deleteScheduleVersionWindow = deleteScheduleVersionWindow;

  bindScheduleVersionWindowForm();
})(jQuery);
