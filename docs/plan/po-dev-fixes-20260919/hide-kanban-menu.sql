-- -----------------------------------------------------------------------------
-- 1. 检查当前菜单状态
-- -----------------------------------------------------------------------------
SELECT `id`, `parentId`, `title`, `icon`, `path`, `perm`, `type`, `sort`, `deletedAt`, `updatedAt`
FROM `zt_menus`
WHERE `path` IN ('/kanban/story', '/kanban/task');

-- -----------------------------------------------------------------------------
-- 2. 执行隐藏：将指向 /kanban/story 和 /kanban/task 的菜单项标记为已删除（隐藏）
-- -----------------------------------------------------------------------------
UPDATE `zt_menus`
SET `deletedAt` = NOW(3),
    `updatedAt` = NOW(3)
WHERE `path` IN ('/kanban/story', '/kanban/task')
  AND `deletedAt` IS NULL;

